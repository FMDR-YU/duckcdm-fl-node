"""Reliability and consistency check of the v1 policy audit (6 platforms x 5 dimensions).

Reads workbook_v1_frozen.csv, a byte copy of safe-model-bundle/poc/policy_audit_workbook.csv
(sha256 below), recomputes the inter-coder numbers reported in the PLOS ONE / HIR
manuscripts and S1 File S4, and writes out/check_v1.md. Nothing is re-coded here.

Method as in safe-model-bundle/poc/kappa_policy_audit.py: complete coder pairs only,
labels normalised (case, dash type, whitespace), Cohen's kappa, 95% interval from a
percentile bootstrap over cells (2000 resamples, numpy default_rng(20260813)).

Usage:  python analysis/policy_audit/check_v1.py        (numpy only; scikit-learn optional)
"""
from __future__ import annotations

import csv
import hashlib
import os
import sys
from collections import Counter, OrderedDict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
WORKBOOK = os.path.join(HERE, "workbook_v1_frozen.csv")
OUT = os.path.join(HERE, "out", "check_v1.md")

EXPECTED_SHA256 = "17af04fe3221443428668b9f50f2df7b320012d5a3bf30c8ca337acf6345baa5"
PUBLISHED = {  # S1 File S4, HIR manuscript Methods
    "overall": (0.77, 0.61, 0.92, 29),
    "D1": (0.11, 6), "D2": (1.00, 6), "D3": (1.00, 6), "D4": (0.33, 6), "D5": (1.00, 5),
}
SEED, N_BOOT = 20260813, 2000
# Update dates shown on the pages when the second coder retrieved them (August 2026), from the second coder's
# confirmation request of 2026-08-19 and the workbook notes. UKB Fees (2026-04-14) predates the baseline.
LATE_VERSIONS = {
    "S5-07": "2026-08-14 (All of Us Data User Code of Conduct)",
    "S5-18": "2026-07-30 (All of Us Policy Questions)",
    "S5-19": "2026-06-15 (All of Us Using Initial Credits)",
    "S5-20": "2026-07-29 (All of Us Costs)",
    "S5-28": "2026-06-12 (Mayo Clinic Platform Accelerate)",
}

PLATFORM_SHORT = OrderedDict([
    ("UK Biobank RAP", "UKB"),
    ("All of Us", "AoU"),
    ("EHDS Secure Processing Environment", "EHDS"),
    ("CODA", "CODA"),
    ("K-CURE", "K-CURE"),
    ("Mayo Clinic Platform", "Mayo"),
])
DIMS = ["D1", "D2", "D3", "D4", "D5"]


def norm(s: str) -> str:
    s = str(s).strip().lower().replace("–", "-").replace("—", "-")
    return " ".join(s.split())


def kappa(a, b) -> float:
    a = [str(x) for x in a]
    b = [str(x) for x in b]
    n = len(a)
    labels = sorted(set(a) | set(b))
    ix = {l: i for i, l in enumerate(labels)}
    m = np.zeros((len(labels), len(labels)))
    for x, y in zip(a, b):
        m[ix[x], ix[y]] += 1
    po = np.trace(m) / n
    pe = float((m.sum(1) * m.sum(0)).sum()) / (n * n)
    if pe >= 1.0:
        return float("nan")
    return (po - pe) / (1.0 - pe)


def kappa_ci(a, b):
    a = np.asarray(a)
    b = np.asarray(b)
    if len(a) < 2 or len(set(a.tolist()) | set(b.tolist())) < 2:
        return float("nan"), float("nan")
    rng = np.random.default_rng(SEED)
    idx = np.arange(len(a))
    stats = []
    for _ in range(N_BOOT):
        s = rng.choice(idx, size=len(idx), replace=True)
        stats.append(kappa(a[s], b[s]))
    return float(np.nanpercentile(stats, 2.5)), float(np.nanpercentile(stats, 97.5))


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def main() -> int:
    raw = open(WORKBOOK, "rb").read()
    sha = hashlib.sha256(raw).hexdigest()
    rows = list(csv.DictReader(open(WORKBOOK, encoding="utf-8-sig", newline="")))
    assert len(rows) == 30, f"expected 30 cells, found {len(rows)}"
    lines = []
    w = lines.append

    w("# v1 policy audit: reliability and consistency check")
    w("")
    w("Generated by `analysis/policy_audit/check_v1.py` from `workbook_v1_frozen.csv`. No cell was re-coded.")
    w("")
    w(f"- workbook sha256: `{sha}` ({'matches' if sha == EXPECTED_SHA256 else 'DOES NOT MATCH'} the frozen copy of 2026-10-12)")
    w(f"- cells: {len(rows)} (6 platforms x 5 dimensions)")
    w("")

    # ---- agreement ----------------------------------------------------------------
    pairs = [(r["dimension"], norm(r["coder_HY"]), norm(r["coder_JL"]))
             for r in rows if r["coder_HY"].strip() and r["coder_JL"].strip()]
    a_all = [p[1] for p in pairs]
    b_all = [p[2] for p in pairs]
    k_all = kappa(a_all, b_all)
    lo, hi = kappa_ci(a_all, b_all)
    agree_all = sum(x == y for x, y in zip(a_all, b_all))

    try:  # optional cross-check of the hand-written kappa against scikit-learn
        from sklearn.metrics import cohen_kappa_score
        sk = cohen_kappa_score(a_all, b_all)
        sk_note = f"scikit-learn cross-check: {sk:.6f} ({'same' if abs(sk - k_all) < 1e-9 else 'DIFFERENT'})"
    except Exception:
        sk_note = "scikit-learn not available; cross-check skipped"

    per_dim = OrderedDict()
    for d in DIMS:
        aa = [p[1] for p in pairs if p[0] == d]
        bb = [p[2] for p in pairs if p[0] == d]
        per_dim[d] = (kappa(aa, bb), sum(x == y for x, y in zip(aa, bb)), len(aa))

    w("## 1. Inter-coder agreement (first coder HY, second coder JL, blind)")
    w("")
    tbl = [["Overall", f"{k_all:.3f}", f"[{lo:.3f}, {hi:.3f}]", f"{agree_all}/{len(pairs)}",
            f"{PUBLISHED['overall'][0]:.2f} [{PUBLISHED['overall'][1]:.2f}, {PUBLISHED['overall'][2]:.2f}], n={PUBLISHED['overall'][3]}"]]
    for d in DIMS:
        k, ag, n = per_dim[d]
        pk, pn = PUBLISHED[d]
        tbl.append([d, "nan" if k != k else f"{k:.3f}", "-", f"{ag}/{n}", f"{pk:.2f}, n={pn}"])
    w(md_table(["Scope", "kappa (recomputed)", "95% CI (bootstrap over cells)", "exact agreement", "as published"], tbl))
    w("")
    w(f"{sk_note}.")
    w("")
    ok = (round(k_all, 2) == PUBLISHED["overall"][0] and round(lo, 2) == PUBLISHED["overall"][1]
          and round(hi, 2) == PUBLISHED["overall"][2] and len(pairs) == PUBLISHED["overall"][3]
          and all(round(per_dim[d][0], 2) == PUBLISHED[d][0] and per_dim[d][2] == PUBLISHED[d][1] for d in DIMS))
    w(f"Reproduction of the published numbers: **{'PASS' if ok else 'FAIL'}**.")
    w("")
    w("With 5 or 6 cells per dimension a dimension-level kappa has no usable interval; the D1 (0.11) and D4 (0.33) values "
      "show where the v1 codebook was ambiguous, not how reliable those dimensions are in general.")
    w("")

    # ---- disagreements -------------------------------------------------------------
    w("## 2. Disagreements and how they were resolved")
    w("")
    dis = []
    for r in rows:
        hy, jl, rec = r["coder_HY"].strip(), r["coder_JL"].strip(), r["reconciled_Table1"].strip()
        if norm(hy) != norm(jl):
            who = ("second coder (JL)" if norm(rec) == norm(jl)
                   else "first coder (HY)" if norm(rec) == norm(hy) else "neither (new category)")
            dis.append([PLATFORM_SHORT[r["platform"]], r["dimension"], hy, jl or "(blank)", rec, who, r["confidence"]])
    w(md_table(["Platform", "Dim", "First coder", "Second coder", "Reconciled (Table 1)", "Reconciled value taken from", "2nd-coder confidence"], dis))
    w("")
    c = Counter(d[5] for d in dis)
    w(f"{len(dis)} cells differ ({', '.join(f'{v} resolved to {k}' for k, v in c.items())}). "
      "Every reconciliation moved the first coder's code, so the reported Table 1 equals the second coder's coding "
      "on all six disagreements and is a new category on the seventh (CODA cost basis, left blank by the second coder).")
    w("")

    # ---- confidence -----------------------------------------------------------------
    w("## 3. Confidence recorded by the second coder at coding time (not re-rated after reconciliation)")
    w("")
    conf = Counter(r["confidence"].strip() for r in rows)
    w(f"high {conf['high']}, med {conf['med']}, uncertain {conf['uncertain']} of {len(rows)} cells.")
    w("")
    hdr = ["Platform"] + DIMS
    body = []
    for p, short in PLATFORM_SHORT.items():
        cells = {r["dimension"]: r["confidence"].strip() for r in rows if r["platform"] == p}
        body.append([short] + [cells[d] for d in DIMS])
    w(md_table(hdr, body))
    w("")
    unc = [f"{PLATFORM_SHORT[r['platform']]} {r['dimension']}" for r in rows if r["confidence"].strip() == "uncertain"]
    w("Uncertain cells: " + ", ".join(unc) + ".")
    w("")

    # ---- trained-model status --------------------------------------------------------
    w("## 4. What the reconciled v1 codes say about trained models (D1 model tier and D2)")
    w("")
    rec = {(r["platform"], r["dimension"]): r for r in rows}
    body = []
    for p, short in PLATFORM_SHORT.items():
        d1, d2 = rec[(p, "D1")], rec[(p, "D2")]
        body.append([short, d1["reconciled_Table1"], d1["confidence"], d2["reconciled_Table1"], d2["confidence"]])
    w(md_table(["Platform", "D1 reconciled", "D1 conf.", "D2 reconciled", "D2 conf."], body))
    w("")
    d2c = Counter(norm(rec[(p, 'D2')]['reconciled_Table1']) for p in PLATFORM_SHORT)
    d1m = sum("model release" in rec[(p, 'D1')]['reconciled_Table1'].lower() for p in PLATFORM_SHORT)
    w("D2 counts: " + "; ".join(f"{k}: {v}" for k, v in d2c.items()) + f". D1 coded as conditional model release: {d1m} of 6.")
    w("")
    w("Reading: model export is described by 3 of 6 platforms (two conditional on a leakage basis, one algorithm-out by design) "
      "and not mentioned by the other 3 (two of those, CODA and K-CURE, uncertain). The v1 manuscript's phrase that a trained "
      "model was an 'empty export category' in all six platforms is therefore not supported; see docs/PLATFORM_EXPORT_MATRIX.md section 3.")
    w("")

    # ---- source register -----------------------------------------------------------
    import re
    cited = OrderedDict()
    for r in rows:
        for part in r["source"].split(";"):
            m = re.match(r"\s*(S5-\d+)\s*(.*)", part)
            if m:
                e = cited.setdefault(m.group(1), {"title": m.group(2).strip(), "cells": []})
                cell = f"{PLATFORM_SHORT[r['platform']]} {r['dimension']}"
                if cell not in e["cells"]:
                    e["cells"].append(cell)
    w("## 5. Source register implied by the workbook (S5 document ids cited as evidence)")
    w("")
    body = []
    for sid in sorted(cited):
        e = cited[sid]
        late = LATE_VERSIONS.get(sid, "")
        body.append([sid, e["title"][:90], ", ".join(e["cells"]), late])
    w(md_table(["Id", "Title as cited in the workbook", "Cells that cite it", "Displayed update date after the 2026-05 baseline"], body))
    w("")
    w(f"{len(cited)} documents are cited. The workbook records no per-document URL, retrieval date or file hash; "
      "only platform-level URLs and the access date 2026-06-07 are recorded (S1 File S3). The documents marked above "
      "carry update dates after May 2026 (second coder's request of 2026-08-19, workbook notes), so for those cells "
      "'current to May 2026' is not established. Ids S5-09 to S5-11 are search scope only or uncited.")
    w("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\nwritten: {OUT}")
    return 0 if ok and sha == EXPECTED_SHA256 else 1


if __name__ == "__main__":
    sys.exit(main())
