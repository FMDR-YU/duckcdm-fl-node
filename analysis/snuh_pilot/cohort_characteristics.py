# -*- coding: utf-8 -*-
"""Cohort description table for TRIPOD+AI (internal review C4): rows, training / validation split, outcome events and rate,
age (mean, SD), sex, number of predictors and the predictors with the most missing values, per analysis cohort. Aggregates
only (every count shown is at least 11; smaller counts are written as <11). Each cohort is read in a child process with its
own PILOT_TAG, because pilot_lib fixes the matrix tag at import.

    python cohort_characteristics.py [--irb E-...]      -> out/cohort_characteristics.md
    python cohort_characteristics.py --one DATASET TAG   (internal: one table row and the predictor line, as JSON)
"""
import argparse
import json
import os
import subprocess
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))

# (label, dataset, tag, age column, sex column, value meaning male)
COHORTS = [('DE-SynPUF (development)', 'synpuf', '', 'age', 'sex', None),
           ('SNUH CKD CDM, training cohort', 'snuh', 'cdmv', 'Age', 'Sex_Male', 1),
           ('eICU-CRD, 3 largest hospitals', 'eicu', 'h3a', 'age', 'gender', None),
           ('eICU-CRD, 3 hospitals of unequal size', 'eicu', 'h3b', 'age', 'gender', None),
           ('eICU-CRD, 14 hospitals', 'eicu', 'h14', 'age', 'gender', None),
           ('eICU-CRD, random sample (canary benchmark only)', 'eicu', 's28k', 'age', 'gender', None),
           ('MIMIC-IV-ED, sample (canary benchmark only)', 'mimic_ed', 's28k', 'age', 'gender', None)]
OUTCOME = {'synpuf': 'synthetic end-stage renal disease indicator', 'snuh': 'eGFR fall to below 60% of baseline or below 15 within 730 days',
           'eicu': 'hospital mortality', 'mimic_ed': 'hospital admission from the emergency department'}


def one(ds, tag, age_col, sex_col, male_value):
    sys.path.insert(0, HERE)
    import pilot_lib as L  # noqa: E402
    cell = lambda n: f'{int(n):,}' if n >= L.MIN_CELL else '<11'  # noqa: E731
    X, y, split, aux, meta = L.load_matrix(ds)
    n = len(y); ntr = int((split == 'train').sum()); nva = int((split == 'val').sum())
    ev = int(y.sum())
    age = pd.to_numeric(X[age_col], errors='coerce') if age_col in X else pd.Series(dtype=float)
    age_txt = f'{age.mean():.1f} ({age.std():.1f})' if len(age.dropna()) else 'n/a'
    sex_txt = 'n/a'
    if sex_col in X:
        s = X[sex_col]
        if male_value is not None:
            male = int((s == male_value).sum())
        elif pd.api.types.is_numeric_dtype(s):
            male = int((s == 1).sum())
        else:
            male = int(s.astype(str).str.lower().isin(['male', 'm', '1', 'true']).sum())
        if male >= L.MIN_CELL:
            sex_txt = f'{cell(male)} ({male / n:.1%})'
    m = X.isna().mean().sort_values(ascending=False)
    top = ', '.join(f'{c} {v:.0%}' for c, v in m.head(3).items() if v > 0) or 'none'
    return {'n': n, 'ntr': ntr, 'nva': nva, 'events': cell(ev), 'rate': f'{ev / n:.1%}', 'age': age_txt, 'sex': sex_txt,
            'p': int(X.shape[1]), 'missing': top, 'features': list(meta['features'])}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--irb', default=os.environ.get('PILOT_IRB', ''))
    ap.add_argument('--one', nargs=2, metavar=('DATASET', 'TAG'))
    a = ap.parse_args()
    if a.irb:
        os.environ['PILOT_IRB'] = a.irb
    if a.one:
        ds, tag = a.one
        spec = next(c for c in COHORTS if c[1] == ds and c[2] == tag)
        print(json.dumps(one(ds, tag, *spec[3:])))
        return
    rows, feats = [], []
    for label, ds, tag, *_ in COHORTS:
        env = dict(os.environ)
        if tag:
            env['PILOT_TAG'] = tag
        else:
            env.pop('PILOT_TAG', None)
        env['PYTHONIOENCODING'] = 'utf-8'
        r = subprocess.run([sys.executable, os.path.abspath(__file__), '--one', ds, tag], env=env, capture_output=True, text=True, encoding='utf-8')
        if r.returncode != 0 or not r.stdout.strip():
            rows.append(f'| {label} | not available | | | | | | |')
            print('  !!', label, (r.stderr or '').strip().splitlines()[-1:] )
            continue
        d = json.loads(r.stdout.strip().splitlines()[-1])
        rows.append(f'| {label} | {d["n"]:,} | {d["ntr"]:,} / {d["nva"]:,} | {d["events"]} ({d["rate"]}) | {d["age"]} | {d["sex"]} | {d["p"]} | {d["missing"]} |')
        feats.append(f'- {label} ({OUTCOME[ds]}): {d["p"]} predictors: ' + ', '.join(d['features']))
    md = ['# Cohort characteristics (TRIPOD+AI items on participants, outcome, predictors and missing data)', '',
          'Generated by cohort_characteristics.py from the analysis matrices; aggregates only, counts below 11 shown as <11. Age is at the index date; '
          'sex is the number and share of men. "Missing" lists the three predictors with the most missing values before model fitting (XGBoost reads missing values natively; the ensemble family imputes medians fit on the training rows).', '',
          '| Cohort | Patients | Training / validation | Outcome events (rate) | Age, mean (SD) | Men, n (%) | Predictors | Missing, top three |', '|---|---|---|---|---|---|---|---|'] + rows
    md += ['', '## Outcomes and predictor lists', ''] + feats + ['']
    out = os.path.join(HERE, 'out', 'cohort_characteristics.md')
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(md) + '\n')
    print('wrote', out)
    print('\n'.join(rows))


if __name__ == '__main__':
    main()
